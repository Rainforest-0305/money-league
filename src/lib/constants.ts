export const TARGET_CONTRACT_NOTIONAL_USD = 5_000;
export const CONTRACT_SIZE_LADDER = [10, 5, 2, 1, 0.5, 0.2, 0.1, 0.05, 0.02, 0.01] as const;

/**
 * 개시가 → 계약 크기. ★이 게임에서 계약 크기를 «말할 수 있는 단 하나»의 함수다.
 * ⛔화면·봇·검사기가 각자 세지 마라. 엔진은 `world.sharesPerContractOf(ticker)` 로,
 *   화면은 `store.sharesPerContractOf(ticker)` 로 «결과»만 받는다(U-7).
 * ★사다리 맨 아래(0.01)보다도 비싼 자산이 나오면 그 값으로 «고정»된다 — 실패하지 않는다.
 */
export function sharesPerContractFor(initialPrice: number): number {
  if (!Number.isFinite(initialPrice) || initialPrice <= 0) return SHARES_PER_CONTRACT;
  for (const v of CONTRACT_SIZE_LADDER) {
    if (v * initialPrice <= TARGET_CONTRACT_NOTIONAL_USD) return v;
  }
  return CONTRACT_SIZE_LADDER[CONTRACT_SIZE_LADDER.length - 1];
}

